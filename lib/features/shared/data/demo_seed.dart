  static PartyEvent _event({
    required String id,
    required UserProfile host,
    required String title,
    required EventCategory category,
    required String area,
    required String city,
    required DateTime start,
    required DateTime end,
    required int spots,
    required int max,
    required int imageId,
    required List<EventTag> tags,
    required List<String> genres,
    required bool boosted,
    required String exactAddress,
  }) {
    final now = DateTime.now();
    final point = city == 'Paris'
        ? GeoPointLite(
            latitude: 48.8566 + imageId % 7 / 1000,
            longitude: 2.3522 + imageId % 9 / 1000,
          )
        : const GeoPointLite(latitude: 43.5528, longitude: 7.0174);
    return PartyEvent(
      id: id,
      hostId: host.id,
      hostPreview: HostPreview(
        id: host.id,
        firstName: host.firstName,
        photoUrl: host.mainPhotoUrl ?? host.profilePhotos.first,
        badges: host.badges,
        hostedEventCount: host.hostedEventCount,
      ),
      title: title,
      description:
          'A private night plan with curated music, clear rules, and a respectful guest list.',
      category: category,
      coverPhotoUrl: 'https://picsum.photos/id/$imageId/1200/1600',
      photoUrls: [
        'https://picsum.photos/id/$imageId/1200/1600',
        'https://picsum.photos/id/${imageId + 1}/1200/1600',
        'https://picsum.photos/id/${imageId + 2}/1200/1600',
      ],
      city: city,
      areaName: area,
      approximateGeoPoint: point,
      exactAddress: exactAddress,
      accessInstructions:
          'Address appears only after host approval. Ring the bell once.',
      startDateTime: start,
      endDateTime: end,
      timezone: 'Europe/Paris',
      ageRequirement: 18,
      maxParticipants: max,
      availableSpots: spots,
      acceptedParticipantIds: id == 'event-006' ? const ['user-001'] : const [],
      waitingParticipantIds: id == 'event-001' ? const ['user-003'] : const [],
      rejectedParticipantIds: const [],
      eventTags: tags,
      musicGenres: genres,
      dressCode: tags.contains(EventTag.dressCode)
          ? 'All black, clean sneakers.'
          : 'Night casual.',
      contributionText: 'Bring drinks if you can.',
      houseRules:
          'Respect the address, no harassment, no public address sharing.',
      alcoholPolicy: tags.contains(EventTag.noAlcohol)
          ? AlcoholPolicy.notAllowed
          : AlcoholPolicy.byob,
      smokingPolicy: tags.contains(EventTag.smokeFriendly)
          ? SmokingPolicy.smokeFriendly
          : SmokingPolicy.outdoorOnly,
      visibility: EventVisibility.public,
      status: start.isBefore(now) && end.isAfter(now)
          ? EventStatus.ongoing
          : EventStatus.published,
      approvalMode: ApprovalMode.manual,
      allowsGroups: tags.contains(EventTag.groupsWelcome),
      maxGroupSize: tags.contains(EventTag.groupsWelcome) ? 4 : 2,
      isBoosted: boosted,
      boostEndDate: boosted ? now.add(const Duration(hours: 6)) : null,
      likeCount: imageId % 23 + 8,
      requestCount: id == 'event-001' ? 1 : imageId % 9,
      matchCount: id == 'event-006' ? 1 : imageId % 5,
      createdAt: now.subtract(Duration(hours: imageId % 12 + 1)),
      updatedAt: now,
      expiresAt: end.add(const Duration(hours: 2)),
    );
  }

